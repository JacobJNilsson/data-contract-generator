// TestMergeKeyColumnsSurrogatePrimaryKeyKeptWhenNoBusinessCandidate: with no
// non-surrogate UNIQUE constraint to override with (either none at all, or
// every one touches a surrogate column), the surrogate primary key is kept.
func TestMergeKeyColumnsSurrogatePrimaryKeyKeptWhenNoBusinessCandidate(t *testing.T) {
	facts := map[string]pgintrospect.Column{
		"id":      identityColumn("t", "id"),
		"ext":     identityColumn("t", "ext"),
		"account": naturalColumn("t", "account", "text"),
	}
	uniques := []odcs.UniqueConstraint{
		uc("t_ext_account_key", "ext", "account"), // touches the surrogate "ext"
	}
	got, err := MergeKeyColumns("t", []string{"id"}, uniques, facts)
	if err != nil {
		t.Fatalf("MergeKeyColumns() error = %v, want nil", err)
	}
	if len(got) != 1 || got[0] != "id" {
		t.Errorf("MergeKeyColumns() = %v, want [id] (no non-surrogate candidate)", got)
	}

	got, err = MergeKeyColumns("t", []string{"id"}, nil, facts)
	if err != nil {
		t.Fatalf("MergeKeyColumns() error = %v, want nil", err)
	}
	if len(got) != 1 || got[0] != "id" {
		t.Errorf("MergeKeyColumns() = %v, want [id] (no unique constraints at all)", got)
	}
}

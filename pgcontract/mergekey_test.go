// TestMergeKeyColumnsSurrogatePrimaryKeyOverriddenByNarrowestBusinessKey: a
// single-column surrogate primary key is overridden by the narrowest UNIQUE
// constraint that touches no surrogate column. It also carries an
// empty-column unique entry, defensively skipped rather than treated as a
// zero-width candidate.
func TestMergeKeyColumnsSurrogatePrimaryKeyOverriddenByNarrowestBusinessKey(t *testing.T) {
	facts := map[string]pgintrospect.Column{
		"id":      identityColumn("t", "id"),
		"account": naturalColumn("t", "account", "text"),
		"date":    naturalColumn("t", "date", "date"),
		"sku":     naturalColumn("t", "sku", "text"),
	}
	uniques := []odcs.UniqueConstraint{
		uc("t_empty_key"),
		uc("t_account_date_key", "account", "date"),
		uc("t_sku_key", "sku"),
	}
	got, err := MergeKeyColumns("t", []string{"id"}, uniques, facts)
	if err != nil {
		t.Fatalf("MergeKeyColumns() error = %v, want nil", err)
	}
	if len(got) != 1 || got[0] != "sku" {
		t.Errorf("MergeKeyColumns() = %v, want [sku] (narrowest non-surrogate candidate)", got)
	}
}

// TestMergeKeyColumnsGeneratedAlwaysPrimaryKeyOverridden: a single-column
// primary key flagged ONLY through IsGenerated ("ALWAYS"), never IsIdentity
